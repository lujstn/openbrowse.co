import { readFile, rm, writeFile } from "node:fs/promises";
import { generateFiles } from "fumadocs-openapi";
import { createOpenAPI } from "fumadocs-openapi/server";

const OUT = "./content/docs/api";
const SPEC = "./data/openapi.json";

await rm(OUT, { recursive: true, force: true });

await generateFiles({
  input: createOpenAPI({ input: [SPEC] }),
  output: OUT,
  per: "operation",
  // @nonobvious(forced-by) groupBy 'tag' emits zero files in fumadocs-openapi 11.2.4 even though every operation carries a tag; 'route' is the working grouping and gives cleaner URLs anyway
  groupBy: "route",
  meta: true,
});

const METHODS = ["get", "post", "put", "patch", "delete"];
const spec = JSON.parse(await readFile(SPEC, "utf8"));

// @nonobvious(must-hold) fumadocs-openapi emits pages with empty structuredData, so the whole v3 reference is invisible to the client-side search index unless the operation's own vocabulary is written back into the frontmatter
function schemaTerms(node, seen = new Set(), depth = 0) {
  if (!node || depth > 4) return [];
  if (typeof node.$ref === "string") {
    const name = node.$ref.split("/").pop();
    if (seen.has(name)) return [];
    seen.add(name);
    return schemaTerms(spec.components?.schemas?.[name], seen, depth + 1);
  }
  const terms = [];
  if (node.properties) {
    for (const [key, value] of Object.entries(node.properties)) {
      terms.push(key);
      terms.push(...schemaTerms(value, seen, depth + 1));
    }
  }
  for (const key of ["items", "allOf", "anyOf", "oneOf"]) {
    const value = node[key];
    if (Array.isArray(value)) {
      for (const entry of value) terms.push(...schemaTerms(entry, seen, depth + 1));
    } else if (value) {
      terms.push(...schemaTerms(value, seen, depth + 1));
    }
  }
  return terms;
}

function searchableText(route, method, operation) {
  const parts = [
    `${method.toUpperCase()} ${route}`,
    operation.summary,
    operation.description,
  ].filter(Boolean);

  const params = (operation.parameters ?? [])
    .map((p) => p.name)
    .filter(Boolean);
  if (params.length) parts.push(`Parameters: ${params.join(", ")}`);

  const body =
    operation.requestBody?.content?.["application/json"]?.schema ?? null;
  const bodyTerms = [...new Set(schemaTerms(body))];
  if (bodyTerms.length) parts.push(`Request body fields: ${bodyTerms.join(", ")}`);

  const ok = operation.responses?.["200"] ?? operation.responses?.["201"];
  const responseTerms = [
    ...new Set(schemaTerms(ok?.content?.["application/json"]?.schema ?? null)),
  ];
  if (responseTerms.length)
    parts.push(`Response fields: ${responseTerms.join(", ")}`);

  parts.push(`Status codes: ${Object.keys(operation.responses ?? {}).join(", ")}`);

  return parts;
}

const operations = [];
for (const [route, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    if (!item[method]) continue;
    operations.push({
      method: method.toUpperCase(),
      route,
      summary: item[method].summary ?? "",
      href: `/docs/api${route.replace(/\{([^}]+)\}/g, "$1")}/${method}`,
    });
  }
}

for (const [route, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    if (!item[method]) continue;
    const file = `${OUT}${route.replace(/\{([^}]+)\}/g, "$1")}/${method}.mdx`;
    let mdx = await readFile(file, "utf8").catch(() => null);
    if (!mdx) continue;

    const lines = searchableText(route, method, item[method]);
    const yaml = lines
      .map((line) => `      - content: ${JSON.stringify(line)}`)
      .join("\n");

    // @nonobvious(forced-by) the renderer resolves the server URL on the client, so the exported HTML ships "Server URL loading..." and a curl to example.com; this writes a correct example into the crawlable body, which is the copy a retriever will quote
    const operation = item[method];
    const bodyExample =
      method === "get" || method === "delete"
        ? ""
        : ` \\\n  -H "Content-Type: application/json" \\\n  -d '{}'`;
    const example = `\n${operation.summary ? `${operation.summary}. ` : ""}Send this to your own instance, replacing \`your-host\` with the hostname it answers on.\n\n\`\`\`bash\ncurl -X ${method.toUpperCase()} "https://your-host${route}" \\\n  -H "Authorization: Bearer $OPENBROWSE_API_KEY"${bodyExample}\n\`\`\`\n`;

    mdx = mdx.replace(
      /(\n\{\/\* This file was generated by Fumadocs[^\n]*\*\/\}\n)/,
      `$1${example}`,
    );

    let patched;
    if (mdx.includes("    contents: []")) {
      patched = mdx.replace("    contents: []", `    contents:\n${yaml}`);
    } else if (mdx.includes("    contents:\n")) {
      patched = mdx.replace("    contents:\n", `    contents:\n${yaml}\n`);
    } else {
      console.warn(
        `could not inject search text into ${file}; the frontmatter shape changed and the v3 reference will not be searchable`,
      );
      continue;
    }
    await writeFile(file, patched);
  }
}

const grouped = new Map();
for (const op of operations) {
  const resource = op.route.split("/")[2];
  if (!grouped.has(resource)) grouped.set(resource, []);
  grouped.get(resource).push(op);
}

const RESOURCE_BLURB = {
  sessions:
    "A session is one agent run. Create one with a task, a model and an output schema, then poll it or read its message stream while it works.",
  profiles:
    "A profile is a persistent browser storage jar, cookies plus localStorage per origin. Attach one to a session and the agent starts already signed in.",
};

const sections = [...grouped.entries()]
  .map(([resource, ops]) => {
    const rows = ops
      .map(
        (op) =>
          `| [${op.summary}](${op.href}) | \`${op.method}\` | \`${op.route}\` |`,
      )
      .join("\n");
    return `## ${resource[0].toUpperCase()}${resource.slice(1)}

${RESOURCE_BLURB[resource] ?? ""}

| Operation | Method | Path |
| --- | --- | --- |
${rows}`;
  })
  .join("\n\n");

const index = `---
title: v3 API reference
description: Every endpoint in the OpenBrowse v3 REST API, the same surface the browser-use-sdk client already speaks, generated from the running application's OpenAPI schema.
---

OpenBrowse serves the same v3 REST surface as Browser Use Cloud, so an existing \`browser-use-sdk\` client works against it once you change \`baseUrl\` and \`apiKey\`. These ${operations.length} operations are generated directly from the application's own OpenAPI schema, so they cannot drift from what your instance actually serves.

## Base URL and authentication

Every request goes to your own instance, under \`/v3\`, and carries your bearer token:

\`\`\`bash
curl https://your-host/v3/sessions \\
  -H "Authorization: Bearer $OPENBROWSE_API_KEY"
\`\`\`

The token is the \`API_KEY\` value written to \`.env\` during [installation](/docs/installation). There is no separate account system and no per-task billing: your instance answers to whoever holds that token, which is why [exposing it safely](/docs/exposing) matters.

${sections}

## Errors

Every \`/v3\` error is a JSON envelope with a stable \`code\`, a human-readable \`message\`, a \`resolution\` hint and a legacy \`detail\`; branch and retry on \`code\` rather than on wording. Responses that carry no body by specification (\`204\`, \`304\`, \`1xx\`) stay bodyless, and anything that would exceed a session's \`maxCostUsd\` cap stops the run rather than continuing to spend. See [error handling](/docs/errors) for the full code list and retry policy.
`;

await writeFile(`${OUT}/index.mdx`, index);

console.log(
  `generated ${operations.length} operation pages and an index into ${OUT}`,
);
