import { readFile, writeFile } from "node:fs/promises";

const CFF =
  process.env.OPENBROWSE_CFF ??
  "https://raw.githubusercontent.com/lujstn/openbrowse/main/CITATION.cff";
const OUT = "./data/release.json";

const check = process.argv.includes("--check");

async function load() {
  if (CFF.startsWith("http")) {
    const res = await fetch(CFF, {
      headers: { "user-agent": "openbrowse.co-citation-sync" },
    });
    if (!res.ok) {
      console.error(`could not fetch ${CFF}: HTTP ${res.status}`);
      process.exit(2);
    }
    return res.text();
  }
  return readFile(CFF, "utf8");
}

function field(cff, name, pattern) {
  const match = cff.match(pattern);
  if (!match) {
    console.error(`CITATION.cff no longer carries a parseable ${name}`);
    process.exit(1);
  }
  return match[1].replace(/^"|"$/g, "").trim();
}

const cff = await load();

const release = {
  $comment:
    "Generated by scripts/sync-citation.mjs from the upstream CITATION.cff. Do not edit by hand.",
  version: field(cff, "version", /^version:\s*(.+)$/m),
  doi: field(cff, "doi", /^doi:\s*(.+)$/m),
  dateReleased: field(cff, "date-released", /^date-released:\s*(.+)$/m),
  orcid: field(cff, "orcid", /orcid:\s*"([^"]+)"/),
};

const rendered = JSON.stringify(release, null, 2) + "\n";

if (check) {
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (current !== rendered) {
    console.error(
      `${OUT} is out of date with the upstream CITATION.cff.\n` +
        `The site publishes softwareVersion and the DOI as machine-readable claims, so this must not drift.\n` +
        `Run: node scripts/sync-citation.mjs`,
    );
    process.exit(1);
  }
  console.log(`${OUT} matches the upstream CITATION.cff (version ${release.version})`);
} else {
  await writeFile(OUT, rendered);
  console.log(`wrote ${OUT}: version ${release.version}, DOI ${release.doi}`);
}
